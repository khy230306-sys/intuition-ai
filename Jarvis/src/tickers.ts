export function resolveTicker(raw: string): { symbol: string; name: string; currency: 'KRW' | 'USD' } | null {
  const t = raw.trim()
  if (!t) return null
  const lower = t.toLowerCase()
  const alias = TICKER_ALIASES[lower] || TICKER_ALIASES[t]
  if (alias) return { ...alias }

  // Korean 6-digit code
  if (/^\d{6}$/.test(t)) {
    return { symbol: `${t}.KS`, name: t, currency: 'KRW' }
  }
  if (/^\d{6}\.ks$/i.test(t)) {
    return { symbol: t.toUpperCase(), name: t.slice(0, 6), currency: 'KRW' }
  }
  if (/^\d{6}\.kq$/i.test(t)) {
    return { symbol: t.toUpperCase(), name: t.slice(0, 6), currency: 'KRW' }
  }
  // US ticker
  if (/^[A-Za-z^][A-Za-z0-9.^_-]{0,11}$/.test(t)) {
    return { symbol: t.toUpperCase(), name: t.toUpperCase(), currency: 'USD' }
  }
  return null
}

export function extractTickerFromText(text: string): { symbol: string; name: string; currency: 'KRW' | 'USD' } | null {
  const direct = resolveTicker(text)
  if (direct) return direct

  // longest alias first
  const keys = Object.keys(TICKER_ALIASES).sort((a, b) => b.length - a.length)
  const lower = text.toLowerCase()
  for (const key of keys) {
    if (lower.includes(key.toLowerCase())) return { ...TICKER_ALIASES[key] }
  }

  const code = text.match(/\b(\d{6})\b/)
  if (code) return resolveTicker(code[1])

  const us = text.match(/\b([A-Za-z]{1,5})\b/)
  if (us && TICKER_ALIASES[us[1].toLowerCase()]) return { ...TICKER_ALIASES[us[1].toLowerCase()] }
  if (us && /^[A-Z]{1,5}$/.test(us[1])) return resolveTicker(us[1])

  return null
}
