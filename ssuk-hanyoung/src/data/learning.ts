const BY_ID = Object.fromEntries(LEARNING_GAMES.map((g) => [g.id, g]))

export function getLearningMeta(id: string): GameLearningMeta | undefined {
  return BY_ID[id]
}

export function gamesByCategory(cat: LearningCategory | 'all') {
  if (cat === 'all') return LEARNING_GAMES
  return LEARNING_GAMES.filter((g) => g.category === cat)
}

export function categoryLabel(id: LearningCategory) {
  return CATEGORIES.find((c) => c.id === id)?.ko || id
}
